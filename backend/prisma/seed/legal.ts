/**
 * =============================================================================
 * 약관 시드 (`legal_documents`) — docs/database/README.md §11.3 "시드 (§8 보완)"
 * =============================================================================
 *
 * `/legal/terms`, `/legal/privacy`, `/legal/location` 세 화면이 지금 '준비중입니다' 한 줄인데,
 * 그 문구가 들어갈 자리가 이 테이블이다. 행이 없으면 화면이 계속 비어 있고, 무엇보다
 * `POST /auth/signup` 의 `agreedTermsVersions` 가 **가리킬 대상이 없어** 동의를 기록할 수 없다.
 *
 * 규칙 세 가지:
 *
 * 1. **본문은 플레이스홀더임이 화면에서 드러나야 한다.** 그럴듯한 가짜 약관을 넣으면
 *    법무 검토 없이 배포될 위험이 있다 (§11.3). 그래서 첫 줄이 경고다.
 * 2. **`effective_at` 은 과거 시각** (`SEED_TODAY - 1일`). 미래면 "지금 유효한 버전" 조회가
 *    0건이 되어 화면이 다시 비어 보인다.
 * 3. **id 를 고정한 upsert** 로 재실행이 안전해야 한다 (§8.1 원칙 2).
 *
 * ☆ 행은 불변이다. 문구가 확정되면 이 행을 고치지 말고 **새 버전 행**(`terms/1.1` …)을
 *   만든다 — `user_agreements` 가 `legal_documents.id` 를 가리키므로 행을 고치면 과거 동의의
 *   대상이 소급 변경된다 (§11.3).
 *
 * ☆ 기존 시드 사용자에 대한 `user_agreements` 행은 만들지 않는다. **동의하지 않은 동의 기록을
 *   만드는 것이 이 테이블에서 가장 하지 말아야 할 일이다.** 그 결과 시드 사용자 전원이
 *   "재동의 대상" 으로 계산되는데, 그것이 사실에 맞는 상태다 (§11.3).
 */

export interface SeedLegalDocument {
  /** 고정 id — 재실행 멱등성의 근거 */
  id: string;
  /** terms | privacy | location (about 은 이번 시드 대상이 아니다) */
  slug: string;
  version: string;
  title: string;
  content: string;
  requiresAgreement: boolean;
}

const PLACEHOLDER_NOTICE = [
  '> ⚠ **이 문서는 자리표시자입니다.** 법무 검토를 거친 실제 약관 문구가 아직 없어서,',
  '> 화면과 동의 기록 구조를 검증할 수 있도록 골격만 넣어 두었습니다.',
  '> 이 문구가 보이는 상태로 서비스를 공개하면 안 됩니다.',
  '',
  '실제 문구가 확정되면 이 행을 고치지 않고 **같은 slug 의 새 버전 행**을 추가합니다',
  '(예: `terms` 의 `1.0` → `1.1`). 동의 기록(`user_agreements`)이 문서 버전 id 를 가리키기',
  '때문에, 행을 고치면 과거 동의가 무엇에 대한 동의였는지 알 수 없게 됩니다.',
].join('\n');

function placeholder(sections: string[]): string {
  return [PLACEHOLDER_NOTICE, '', ...sections].join('\n');
}

